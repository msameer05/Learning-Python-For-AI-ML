#In this chapter 2 we will learn about the data types in python and how to use them in our programs. We will cover the following topics:
# 1-integers :-
#           integer data type is used to represent whole numbers. In Python,
#           integers can be of any length, and they can be positive or negative.
number = 10
rank = -5
print(type(number))
print(type(rank))

# 2-floats :-
#           float data type is used to represent decimal numbers. In Python,
#           floats can be of any precision, and they can be positive or negative.
price = 19.99
temperature = -10.5
print(type(price))
print(type(temperature))

# 3-strings :-
#           string data type is used to represent text. In Python, strings are enclosed 
#           in single or double quotes.
name = "Alice"
message = 'Hello, World!'
print(type(name))
print(type(message))

# 4-booleans :-
#           boolean data type is used to represent True or False values.
is_active = True
is_complete = False
print(type(is_active))
print(type(is_complete))

# 5-complex numbers :-
#           complex data type is used to represent numbers with a real and an imaginary part.
complex_number = 3 + 4j
print(type(complex_number))

# 6-None type :-
#           None data type is used to represent the absence of a value.
value = None
print(type(value))