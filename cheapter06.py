#In this cheapter we learn about loops 
#Loops:-
#    there are two types of loops in python language
# 1. FOR LOOP
# 2. WHILE LOOP

#  FOR LOOP :-
#             For loop we use it for a specific range or for a specific times to run or execute our program
# for example:-
for i in range (1,101):
    print("hello world")

#  WHILE LOOP:-
#             While loop we use it for conditions when conditions come we use while loops 
# for example:-
a = 0
while a <= 5:
    print(a)
    a += 1

# you have to be care full in while loop because if you did not stop the loop itwill be infinite
# for example
while True:
    print("hello world") # this is an example of infinite loop
